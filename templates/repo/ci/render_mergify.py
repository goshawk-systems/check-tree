#!/usr/bin/env python3
"""Write `.mergify.yml` from `.mergify.template.yml` and `.check-tree/repo.json`, or check the committed one is current.

The queue's priority rules name your work-item prefixes, so they are generated, never typed:

    render_mergify.py --write     write .mergify.yml
    render_mergify.py --check     exit 1, with a diff, when the committed .mergify.yml is not what --write would write
    render_mergify.py --print     print it

Priority, first matching rule wins (Mergify: docs.mergify.com/merge-queue/priority; low 1000, medium 2000, high 3000):
  4000  the description has a `Fixes-breakage:` line
  low   a Dependabot bump
  high  product work: the title, or a `Closes-item:`/`Refs-item:` trailer, starts with a product prefix
  low   process work: the same, with a process prefix
  low   docs only: every changed file is under docs/ or is markdown
  (anything else is medium, Mergify's default: above process, below product)
Standard library only.
"""
from __future__ import annotations

import argparse
import difflib
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import settings as settings_mod  # noqa: E402

MARKER = "# @@PRIORITY_RULES@@"
HEADER = ("# GENERATED by ci/render_mergify.py from .mergify.template.yml and .check-tree/repo.json. DO NOT EDIT THIS FILE:\n"
          "# edit the template or the settings, then run `python3 ci/render_mergify.py --write`. pr-check.yml fails when this drifts.\n\n")
TRAILER_TAIL = r"-\d+[A-Za-z]?\s*$"


def q(s: str) -> str:
    """A YAML single-quoted scalar."""
    return "'" + s.replace("'", "''") + "'"


def prefixes_regex(prefixes: list[str]) -> str:
    return "|".join(re.escape(p) for p in prefixes)


def rule(name: str, condition: str, priority) -> str:
    return (f"  - name: {q(name)}\n    conditions:\n      - {q(condition)}\n"
            f"    priority: {priority}\n    allow_checks_interruption: false\n")


def priority_rules(settings: dict) -> str:
    product = [p for p in settings.get("product_prefixes", []) if p]
    process = [p for p in settings.get("process_prefixes", []) if p]
    out = [rule("a fix for a red master (Fixes-breakage) goes first of all", r"body~=(?m)^Fixes-breakage:\s*\S+", 4000),
           rule("Dependabot bumps queue behind everything else", "author=dependabot[bot]", "low")]
    if product:
        alt = prefixes_regex(product)
        out.append(rule(f"product work ({', '.join(product)}), by the title's leading id, goes first",
                        rf"title~=^\W*({alt})-\d", "high"))
    if process:
        alt = prefixes_regex(process)
        out.append(rule(f"process work ({', '.join(process)}), by the title's leading id, queues behind product work",
                        rf"title~=^\W*({alt})-\d", "low"))
    if product:
        alt = prefixes_regex(product)
        out.append(rule("product work, by the description's work-item trailer, goes first",
                        rf"body~=(?m)^\s*(Closes|Refs)-item:\s*(?i:{alt}){TRAILER_TAIL}", "high"))
    if process:
        alt = prefixes_regex(process)
        out.append(rule("process work, by the description's work-item trailer, queues behind product work",
                        rf"body~=(?m)^\s*(Closes|Refs)-item:\s*(?i:{alt}){TRAILER_TAIL}", "low"))
    out.append(rule("a docs-only change (every file under docs/ or a markdown file) queues behind product work",
                    r"-files~=^(?!docs/)(?!.*\.md$)", "low"))
    return "".join(out).rstrip("\n")


def render(template: str, settings: dict) -> str:
    if MARKER not in template:
        raise SystemExit(f"the template has no `{MARKER}` line")
    text = template.replace("{{default_branch}}", str(settings["default_branch"]))
    text = text.replace(MARKER, priority_rules(settings))
    return HEADER + text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--print", action="store_true", dest="show")
    ap.add_argument("--template", default=".mergify.template.yml")
    ap.add_argument("--out", default=".mergify.yml")
    ap.add_argument("--settings", default=settings_mod.SETTINGS_PATH)
    a = ap.parse_args(argv)
    rendered = render(pathlib.Path(a.template).read_text(encoding="utf-8"), settings_mod.load(a.settings))
    out = pathlib.Path(a.out)
    if a.show:
        print(rendered, end="")
    elif a.write:
        out.write_text(rendered, encoding="utf-8")
    else:
        have = out.read_text(encoding="utf-8") if out.is_file() else ""
        if have != rendered:
            sys.stdout.writelines(difflib.unified_diff(have.splitlines(True), rendered.splitlines(True),
                                                       f"{a.out} (committed)", f"{a.out} (rendered)"))
            print(f"\n{a.out} is not what `python3 ci/render_mergify.py --write` produces from {a.template} and {a.settings}.")
            return 1
        print(f"{a.out} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
